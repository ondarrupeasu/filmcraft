/// Position class of a raster 4x4 coefficient: 0 both even, 1 both odd, 2 otherwise.
pub const fn pos_class4(i: usize) -> usize {
    let (x, y) = (i & 3, i >> 2);
    if x % 2 == 0 && y % 2 == 0 {
        0
    } else if x % 2 == 1 && y % 2 == 1 {
        1
    } else {
        2
    }
}
