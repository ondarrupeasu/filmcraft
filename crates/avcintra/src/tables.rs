/// A scaling list (zig-zag) as the raster weightScale4x4 matrix (8.5.6).
pub const fn weights(list: &[i32; 16]) -> [i32; 16] {
    let mut w = [0i32; 16];
    let mut k = 0;
    while k < 16 {
        w[ZIGZAG4[k]] = list[k];
        k += 1;
    }
    w
}

